"""回答してはいけない質問（個人の給与・評価・懲戒・健康・法律相談）を検出する。"""
import re

_PERSON = r"(?:私|自分|僕|わたし|俺|同僚|先輩|後輩|上司|部下|社員|[A-Za-zＡ-Ｚ一-龥]{1,4}(?:さん|様))"
_RULES = [
    ("個人の給与・評価・健康情報", re.compile(_PERSON + r".{0,10}(?:給料|給与|年収|評価|査定|考課|健康診断|診断|病気|病院|うつ)")),
    ("個人への懲戒・処分の判断", re.compile(_PERSON + r".{0,8}(?:懲戒|処分|解雇)|(?:懲戒|処分|解雇).{0,6}(?:すべき|してよい|にできる|できますか)")),
    ("休職・復職の個別可否", re.compile(r"(?:私|自分|僕|同僚|部下).{0,15}休職.{0,6}(?:できますか|可能|できる|認められ)")),
    ("法律相談", re.compile(r"違法|訴え|訴訟|裁判|弁護士|慰謝料|損害賠償|勝てる|不当解雇|法的")),
]


def check(question):
    """該当すれば拒否理由を返す。なければ None。"""
    for reason, rx in _RULES:
        if rx.search(question):
            return reason
    return None
